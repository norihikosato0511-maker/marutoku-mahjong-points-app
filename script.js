function calc() {
    const result = document.getElementById("result");
    const handType = document.getElementById("handType").value;
    const player = document.getElementById("player").value;
    const win = document.getElementById("win").value;
    const han = Number(document.getElementById("han").value);

    // 役満
    if (handType === "yakuman") {
        if (player === "child") {
            result.textContent =
                win === "ron"
                    ? "32000点"
                    : "8000 / 16000";
        } else {
            result.textContent =
                win === "ron"
                    ? "48000点"
                    : "16000オール";
        }
        return;
    }

    let fu = document.getElementById("fu").value;

    // 七対子
    if (handType === "chitoi") {
        fu = "25";
    }

    // 数え役満
    if (han >= 13) {
        if (player === "child") {
            result.textContent =
                win === "ron"
                    ? "32000点"
                    : "8000 / 16000";
        } else {
            result.textContent =
                win === "ron"
                    ? "48000点"
                    : "16000オール";
        }
        return;
    }

    const key = fu + "-" + han;

    result.textContent =
        table[player][win][key] || "未登録";
}

window.calc = calc;